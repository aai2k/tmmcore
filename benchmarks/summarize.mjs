/**
 * Join every result file into the cross-library comparison tables.
 *
 * Inputs (produced by the benchmark drivers):
 *   results_py.json       Byrnes, dedicated process, Python complex inputs
 *   results_js.json       tmmcore JS + WASM, single stack
 *   results_fast_t1.json  tmm_faster / tmm_fast / tmmax, pinned to one thread
 *   results_js_batch.json tmmcore JS + WASM, 128-stack batch
 *
 * Byrnes timings come from results_py.json rather than the copy inside
 * results_fast_t1.json: that run shares a process with torch and JAX, so the
 * dedicated measurement is the fairer one.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const read = f => existsSync(join(HERE, f))
    ? JSON.parse(readFileSync(join(HERE, f), 'utf8')) : null;

const py = read('results_py.json');
const js = read('results_js.json');
const fast = read('results_fast_t1.json');
const jsb = read('results_js_batch.json');

if (!py || !js || !fast) {
    console.error('Missing result files — run the benchmark drivers first (see README).');
    process.exit(1);
}

const ms = s => s * 1e3;
const f3 = n => n.toFixed(n < 10 ? 3 : n < 100 ? 2 : 1);
const L = [];

L.push('# TMM kernel benchmark — results');
L.push('');
L.push('Generated by `benchmarks/summarize.mjs`. Method: `benchmarks/README.md`.');
L.push('');
L.push('All figures **single-threaded**, best-of-N, float64. One "spectrum" is every wavelength on the grid for **both** polarizations — the unit an optimizer evaluates thousands of times per design.');
L.push('');
L.push('Grids: `g71` = 400–1100 nm @ 10 nm (71 points), `g701` = @ 1 nm (701 points). Stacks: `AR4` 4-layer AR, `AG7` 7-layer with absorbing Ag, `HR21` 21-layer quarter-wave reflector, `BIG40` 40-layer.');
L.push('');

L.push('## Single stack, one spectrum (ms — lower is better)');
L.push('');
L.push('| case | N | nLam | byrnes | tmm_fast | tmmax | tmm_faster | TFS js | **TFS wasm** |');
L.push('|---|--:|--:|--:|--:|--:|--:|--:|--:|');

const rows = [];
for (const r of js.results) {
    const p = py.results.find(x => x.name === r.name);
    const f = fast.results.find(x => x.name === r.name);
    if (!p || !f) continue;
    const rec = {
        name: r.name, N: r.nLayers, nLam: r.nLam,
        byrnes: ms(p.seconds),
        tmm_fast: ms(f.single.tmm_fast),
        tmmax: ms(f.single.tmmax),
        tmm_faster: ms(f.single.tmm_faster),
        tfs_js: ms(r.js_s),
        tfs_wasm: ms(r.wasm_spec_s),
        diff_cpp: f.diff_vs_byrnes.tmm_faster,
    };
    rows.push(rec);
    L.push(`| ${rec.name} | ${rec.N} | ${rec.nLam} | ${f3(rec.byrnes)} | ${f3(rec.tmm_fast)} `
        + `| ${f3(rec.tmmax)} | ${f3(rec.tmm_faster)} | ${f3(rec.tfs_js)} | **${f3(rec.tfs_wasm)}** |`);
}
L.push('');

L.push('## tmmcore WASM speedup over each library (×, single-threaded)');
L.push('');
L.push('| case | vs byrnes | vs tmm_fast | vs tmmax | vs tmm_faster |');
L.push('|---|--:|--:|--:|--:|');
const agg = { byrnes: [], tmm_fast: [], tmmax: [], tmm_faster: [] };
for (const r of rows) {
    const s = k => r[k] / r.tfs_wasm;
    for (const k of Object.keys(agg)) agg[k].push(s(k));
    L.push(`| ${r.name} | ${s('byrnes').toFixed(0)}× | ${s('tmm_fast').toFixed(1)}× `
        + `| ${s('tmmax').toFixed(1)}× | ${s('tmm_faster').toFixed(1)}× |`);
}
const rng = a => `${Math.min(...a).toFixed(1)}–${Math.max(...a).toFixed(1)}×`;
L.push(`| **range** | **${rng(agg.byrnes)}** | **${rng(agg.tmm_fast)}** `
    + `| **${rng(agg.tmmax)}** | **${rng(agg.tmm_faster)}** |`);
L.push('');

if (jsb) {
    L.push(`## Batch of ${jsb.nbatch} distinct stacks (ms, single-threaded)`);
    L.push('');
    L.push('The vectorized libraries fold this into one call; tmmcore has no batch entry point and simply loops.');
    L.push('');
    L.push('| case | byrnes | tmm_fast | tmm_faster | TFS js | **TFS wasm** |');
    L.push('|---|--:|--:|--:|--:|--:|');
    for (const b of jsb.results) {
        const f = fast.results.find(x => x.name === b.name);
        if (!f || !f.batch) continue;
        L.push(`| ${b.name} | ${f3(ms(f.batch.byrnes))} | ${f3(ms(f.batch.tmm_fast))} `
            + `| ${f3(ms(f.batch.tmm_faster))} | ${f3(ms(b.js_s))} | **${f3(ms(b.wasm_s))}** |`);
    }
    L.push('');
}

L.push('## Agreement with Byrnes');
L.push('');
L.push('Max |difference| in R/T over the whole grid, both polarizations:');
L.push('');
L.push('| case | tmm_faster | tmmcore js + wasm |');
L.push('|---|--:|--:|');
const TFS_DIFF = {   // from bench_js.mjs, js-vs-byrnes column
    'AR4/g71': 2.11e-15, 'HR21/g71': 1.20e-14, 'AG7/g71': 1.44e-15,
    'BIG40/g71': 1.73e-14, 'AR4/g701': 2.55e-15, 'HR21/g701': 2.38e-14,
    'AG7/g701': 3.11e-15, 'BIG40/g701': 8.58e-14,
};
for (const r of rows) {
    const t = TFS_DIFF[r.name];
    L.push(`| ${r.name} | ${r.diff_cpp.toExponential(1)} | ${t ? t.toExponential(1) : 'n/a'} |`);
}
L.push('');
L.push('`tmm_fast` agrees only to ~1e-9 even when fed float64 inputs — it casts internally. Adequate for generating ML training data; not for a design tool whose optimizer converges against far tighter tolerances.');
L.push('');
L.push('`tmmax` reads materials from its own bundled database rather than accepting explicit n,k, so it is timed at matching layer/grid sizes but not value-checked. Its timing also includes an nk interpolation the others do not perform.');
L.push('');

writeFileSync(join(HERE, 'tables.md'), L.join('\n'));
console.log(L.join('\n'));
console.log('\nwrote benchmarks/tables.md — transcribe into docs/comparison.md');
